  { value: 'ja-JP', label: '日本語', shortLabel: '日本語', flag: '🇯🇵' }
]

const currentLanguage = computed(() => locale.value)
const currentLangOption = computed(() => languageOptions.find(l => l.value === currentLanguage.value))

// Login form data
