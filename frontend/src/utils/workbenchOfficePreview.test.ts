const dom = new JSDOM('')
Object.defineProperty(globalThis, 'DOMParser', { value: dom.window.DOMParser, configurable: true })
Object.defineProperty(globalThis, 'XMLSerializer', { value: dom.window.XMLSerializer, configurable: true })
test.after(() => dom.window.close())

const rels = (body: string) => `<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${body}</Relationships>`
const rel = (target: string, mode = '') => `<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="${target}" ${mode}/>`
function presentation() {
  const zip = new JSZip()
  zip.file('[Content_Types].xml', '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"/>')
  zip.file('_rels/.rels', rels(rel('ppt/presentation.xml')))
  zip.file('ppt/presentation.xml', '<presentation/>')
  zip.file('ppt/slides/slide1.xml', '<slide/>')
  zip.file('ppt/slides/_rels/slide1.xml.rels', rels(rel('../media/image1.png')))
  zip.file('ppt/media/image1.png', new Uint8Array([137, 80, 78, 71]))
  return zip
}
async function blob(zip: JSZip) {
  return new Blob([await zip.generateAsync({ type: 'arraybuffer', compression: 'DEFLATE' })])
}
function rejected(code: WorkbenchOfficePreviewError['code']) {
  return (error: unknown) => error instanceof WorkbenchOfficePreviewError && error.code === code
}

test('PPTX keeps slides, internal relative relationships, and embedded images', async () => {
  const zip = presentation()
  zip.file('ppt/slides/slide2.xml', '<slide>Second page</slide>')
  const result = await JSZip.loadAsync(await prepareWorkbenchOfficePreview(await blob(zip), 'pptx'))
  assert.equal(await result.file('ppt/slides/slide2.xml')?.async('text'), '<slide>Second page</slide>')
  assert.deepEqual(await result.file('ppt/media/image1.png')?.async('uint8array'), new Uint8Array([137, 80, 78, 71]))
  assert.equal(Object.values(result.files).some(entry => entry.dir), false)
})

test('validated workbench PPTX remains compatible with the upstream missing-master repair', async () => {
  const zip = presentation()
  const missing = '/ppt/slideMasters/slideMaster2.xml'
  zip.file('[Content_Types].xml', `<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Override PartName="${missing}" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slideMaster+xml"/></Types>`)
  zip.file('ppt/presentation.xml', '<p:presentation xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"><p:sldIdLst><p:sldId id="256"/></p:sldIdLst></p:presentation>')
  const source = await blob(zip)
  const validated = await prepareWorkbenchOfficePreview(source, 'pptx')
  const prepared = await preparePptxPreview(validated)
  assert.equal(prepared.slideCount, 1)
  assert.equal(isCompletePptxRender({ slides: [{}] }, prepared.slideCount), true)
  const repaired = await JSZip.loadAsync(prepared.data)
  assert.ok(!(await repaired.file('[Content_Types].xml')!.async('string')).includes(missing))
  const original = await JSZip.loadAsync(await source.arrayBuffer())
  assert.ok((await original.file('[Content_Types].xml')!.async('string')).includes(missing))
  assert.equal(await repaired.file('ppt/slides/slide1.xml')!.async('string'), '<slide/>')
  assert.deepEqual(await repaired.file('ppt/media/image1.png')!.async('uint8array'), new Uint8Array([137, 80, 78, 71]))
})

test('XLSX generated by the existing spreadsheet library retains multiple sheets and cells', async () => {
  const workbook = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(workbook, XLSX.utils.aoa_to_sheet([['Backend', 'Count'], ['Docker', 7]]), 'Summary')
  XLSX.utils.book_append_sheet(workbook, XLSX.utils.aoa_to_sheet([['Second sheet'], [42]]), 'Details')
  const source = new Blob([XLSX.write(workbook, { type: 'array', bookType: 'xlsx' })])
  const result = XLSX.read(await prepareWorkbenchOfficePreview(source, 'xlsx'), { type: 'array' })
  assert.deepEqual(result.SheetNames, ['Summary', 'Details'])
  assert.equal(result.Sheets.Summary.B2.v, 7)
  assert.equal(result.Sheets.Details.A2.v, 42)
})

