test('Office rejects malformed packages, XML, DTDs, and entity expansion', async () => {
  await assert.rejects(prepareWorkbenchOfficePreview(new Blob(['not a zip']), 'pptx'), rejected('officeInvalid'))
  for (const xml of ['<broken>', '<!DOCTYPE x SYSTEM "https://evil.example/dtd"><x/>', '<!DOCTYPE x [<!ENTITY a "hello">]><x>&a;</x>']) {
    const zip = presentation()
    zip.file('ppt/slides/slide1.xml', xml)
    await assert.rejects(prepareWorkbenchOfficePreview(await blob(zip), 'pptx'), rejected('officeInvalid'))
  }
  await assert.rejects(prepareWorkbenchOfficePreview(await blob(presentation()), 'xlsx'), rejected('officeInvalid'))
})

test('Office bounds input size, entry count, and actual decompressed entry bytes', async () => {
  const normal = await blob(presentation())
  await assert.rejects(prepareWorkbenchOfficePreview(normal, 'pptx', normal.size - 1), rejected('officeTooLarge'))
  const many = presentation()
  for (let i = 0; i < WORKBENCH_OFFICE_LIMITS.entries; i++) many.file(`parts/${i}`, '', { createFolders: false })
  await assert.rejects(prepareWorkbenchOfficePreview(await blob(many), 'pptx'), rejected('officeTooLarge'))
  const large = presentation()
  large.file('large.bin', new Uint8Array(WORKBENCH_OFFICE_LIMITS.entryBytes + 1))
  const compressed = await blob(large)
  assert.ok(compressed.size < 20000)
  await assert.rejects(prepareWorkbenchOfficePreview(compressed, 'pptx'), rejected('officeTooLarge'))
})

test('Office bounds aggregate expanded bytes across individually acceptable entries', async () => {
  const zip = presentation()
  for (let i = 0; i < 5; i++) zip.file(`part${i}.bin`, new Uint8Array(WORKBENCH_OFFICE_LIMITS.entryBytes))
  await assert.rejects(prepareWorkbenchOfficePreview(await blob(zip), 'pptx'), rejected('officeTooLarge'))
})

test('Office expansion limits do not trust forged ZIP size headers', async () => {
  const zip = presentation()
  zip.file('large.bin', new Uint8Array(WORKBENCH_OFFICE_LIMITS.entryBytes + 1))
  const source = Buffer.from(await (await blob(zip)).arrayBuffer())
  let offset = source.indexOf(Buffer.from([0x50, 0x4b, 0x01, 0x02]))
  while (offset !== -1) {
    if (source.readUInt32LE(offset + 24) > WORKBENCH_OFFICE_LIMITS.entryBytes) source.writeUInt32LE(1, offset + 24)
    offset = source.indexOf(Buffer.from([0x50, 0x4b, 0x01, 0x02]), offset + 4)
  }
  await assert.rejects(prepareWorkbenchOfficePreview(new Blob([source]), 'pptx'), rejected('officeTooLarge'))
})

