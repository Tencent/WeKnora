package service

import (
	"context"
	"crypto/sha256"
	"encoding/base64"
	"fmt"
	"strings"

	apperrors "github.com/Tencent/WeKnora/internal/errors"
	"github.com/Tencent/WeKnora/internal/types"
)

type followUpDocumentTargetsKey struct{}

const documentFollowUpHashPrefix = "doc-v1:"

func followUpDocumentTargets(ctx context.Context) types.SearchTargets {
	targets, _ := ctx.Value(followUpDocumentTargetsKey{}).(types.SearchTargets)
	return targets
}

func (s *messageSuggestionService) authorizeFollowUp(
	ctx context.Context, message *types.Message,
) (context.Context, error) {
	scope, hasKey := types.TenantAPIKeyScopeFromContext(ctx)
	restricted := hasKey && scope.IsKnowledgeBaseRestricted()
	snapshot := message.ExecutionContext
	if snapshot.DocumentScopeAPIKeyID == 0 {
		return ctx, nil
	}
	if !restricted || scope.KeyID == 0 || snapshot.DocumentScopeAPIKeyID != scope.KeyID ||
		message.Role != "assistant" || !message.IsCompleted || len(snapshot.KnowledgeIDs) == 0 ||
		len(snapshot.KnowledgeBaseIDs) > 0 || len(snapshot.TagIDs) > 0 || len(snapshot.TagScopes) > 0 {
		return ctx, apperrors.NewForbiddenError("follow-up suggestions require verified documents for this API key")
	}

	// Recheck the live scope before returning cached results or using stored
	// evidence. The key's authorized KBs or a document's owner may have changed.
	targets, err := buildRestrictedAgentDocumentTargets(
		ctx, s.knowledgeService, s.knowledgeBaseService, types.MustTenantIDFromContext(ctx), snapshot.KnowledgeIDs,
	)
	if err != nil {
		return ctx, err
	}
	basesByDocument := followUpDocumentBases(targets)
	for _, ref := range message.KnowledgeReferences {
		if ref == nil {
			continue
		}
		kbID, allowed := basesByDocument[ref.KnowledgeID]
		if !allowed || ref.KnowledgeBaseID != kbID {
			return ctx, apperrors.NewForbiddenError("follow-up evidence is outside the verified document scope")
		}
	}
	return context.WithValue(ctx, followUpDocumentTargetsKey{}, targets), nil
}

func (s *messageSuggestionService) authorizeFollowUpSet(ctx context.Context, set *types.MessageSuggestionSet) error {
	scope, hasKey := types.TenantAPIKeyScopeFromContext(ctx)
	restricted := hasKey && scope.IsKnowledgeBaseRestricted()
	if !restricted && !strings.HasPrefix(set.ConfigHash, documentFollowUpHashPrefix) {
		return nil
	}
	message, err := s.messageService.GetMessage(ctx, set.SessionID, set.AssistantMessageID)
	if err != nil {
		return err
	}
	ctx, err = s.authorizeFollowUp(ctx, message)
	if err != nil {
		return err
	}
	if set.ConfigHash != followUpCacheHash(ctx, message.ExecutionContext) {
		return apperrors.NewForbiddenError("the suggestion set does not match the verified document scope")
	}
	return nil
}

func followUpCacheHash(ctx context.Context, snapshot types.MessageExecutionContext) string {
	configHash := snapshot.AgentConfigHash
	if configHash == "" {
		configHash = "no-agent-config"
	}
	targets := followUpDocumentTargets(ctx)
	if len(targets) == 0 {
		return configHash
	}
	// A recommendation generated by older code or a prior verified scope
	// must not enter the current scope through the agent config cache.
	digest := sha256.New()
	fmt.Fprintf(digest, "%s\x00%d", configHash, snapshot.DocumentScopeAPIKeyID)
	for _, target := range targets {
		fmt.Fprintf(digest, "\x00kb:%s\x00tenant:%d", target.KnowledgeBaseID, target.TenantID)
		for _, id := range target.KnowledgeIDs {
			fmt.Fprintf(digest, "\x00doc:%s", id)
		}
	}
	return documentFollowUpHashPrefix + base64.RawURLEncoding.EncodeToString(digest.Sum(nil))
}

func followUpDocumentBases(targets types.SearchTargets) map[string]string {
	basesByDocument := make(map[string]string)
	for _, target := range targets {
		for _, id := range target.KnowledgeIDs {
			basesByDocument[id] = target.KnowledgeBaseID
		}
	}
	return basesByDocument
}
