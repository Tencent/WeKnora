package session

import (
	"net/http"
	"strings"

	"github.com/Tencent/WeKnora/internal/errors"
	"github.com/Tencent/WeKnora/internal/logger"
	"github.com/Tencent/WeKnora/internal/types"
	"github.com/gin-gonic/gin"
)

// artifactLibraryResponse is the body of ListArtifactLibrary.
type artifactLibraryResponse struct {
	Success  bool                         `json:"success"`
	Data     []*types.ArtifactLibraryItem `json:"data"`
	Total    int64                        `json:"total" extensions:"x-agent"`
	Page     int                          `json:"page" extensions:"x-agent"`
	PageSize int                          `json:"page_size" extensions:"x-agent"`
}

// ListArtifactLibrary godoc
// @Summary      列出我的产物
// @Description  跨会话列出当前用户可见会话中技能生成的文件，每个文件只返回最新版本（不含存储 URL）
// @Tags         会话
// @Produce      json
// @Param        keyword     query  string  false  "按文件名过滤"  extensions(x-agent)
// @Param        file_types  query  string  false  "逗号分隔的扩展名，如 .pdf,.pptx"  extensions(x-agent)
// @Param        page        query  int     false  "页码"  minimum(1)  extensions(x-agent,x-agent-maximum=10000)
// @Param        page_size   query  int     false  "每页数量（最大 100）"  minimum(1)  maximum(100)  extensions(x-agent,x-agent-maximum=20)
// @Success      200  {object}  artifactLibraryResponse
// @Security     Bearer
// @Security     ApiKeyAuth
// @x-agent      {"id":"artifact.list","risk":"read"}
// @x-agent-hint "Files generated by agents across the user's conversations, newest first. This is the Artifacts library, not the current chat's sandbox. keyword matches file names; file_types is a comma-separated list of extensions such as .pdf,.pptx,.md. Each item has file_name, created_at, session_title and session_id. Do not use generated-file or sandbox tools to answer what is on this page."
// @Router       /artifacts [get]
//
// Items carry session_id, message_id and index so the client downloads
// through the per-session endpoint, which re-runs the ownership check.
func (h *Handler) ListArtifactLibrary(c *gin.Context) {
	ctx := c.Request.Context()

	var pagination types.Pagination
	if err := c.ShouldBindQuery(&pagination); err != nil {
		_ = c.Error(errors.NewBadRequestError(err.Error()))
		return
	}
	var fileTypes []string
	if raw := c.Query("file_types"); raw != "" {
		fileTypes = strings.Split(raw, ",")
	}

	result, err := h.messageService.ListArtifactLibrary(ctx, &types.ArtifactLibraryQuery{
		Keyword:   c.Query("keyword"),
		FileTypes: fileTypes,
		Page:      pagination.Page,
		PageSize:  pagination.PageSize,
	})
	if err != nil {
		logger.Errorf(ctx, "list artifact library failed: %v", err)
		_ = c.Error(errors.NewInternalServerError(err.Error()))
		return
	}

	c.JSON(http.StatusOK, gin.H{
		"success":   true,
		"data":      result.Data,
		"total":     result.Total,
		"page":      result.Page,
		"page_size": result.PageSize,
	})
}
